/**
 * Niveaux du jeu de plateformes (mario.js) : 9 rangées de tuiles, la hauteur de l'écran de
 * la Game Boy. Chaque niveau est assemblé de morceaux posés côte à côte ; tous les niveaux
 * finissent par le même escalier, le drapeau et le château.
 *
 * . vide            # sol             X bloc dur          B brique
 * ? bloc à pièce    M bloc champignon H bloc cœur (une vie en plus)
 * o pièce           [ ] haut de tuyau { } tuyau
 * S départ          F haut du mât     C château           g champignon méchant   k tortue
 *
 * `checkpoint` : colonne où l'on repart après avoir perdu une vie, une fois dépassée.
 */

function joinChunks (chunks) {
  return chunks[0].map((_, row) => chunks.map(chunk => chunk[row]).join(''))
}

