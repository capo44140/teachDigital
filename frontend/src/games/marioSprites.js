// Colline en dôme : contour foncé, quelques taches claires (le héros reste bien visible devant)
function makeHill (width, height) {
  const rows = []
  for (let y = 0; y < height; y++) {
    const half = Math.round((width / 2) * Math.sqrt(1 - ((height - 1 - y) / (height - 1)) ** 2))
    const left = width / 2 - half
    const right = width / 2 + half - 1
    let row = ''
    for (let x = 0; x < width; x++) {
      if (x < left || x > right) row += '.'
      else if (x === left || x === right || y === 0) row += '2'
      else row += (x * 7 + y * 13) % 29 === 0 ? '0' : '1'
    }
    rows.push(row)
  }
  return rows
}

// Château de fin de niveau (48 × 40) : tour crénelée, murs de briques, porte
function makeCastle () {
  const width = 48
  const height = 40
  const rows = []
  for (let y = 0; y < height; y++) {
    let row = ''
    for (let x = 0; x < width; x++) {
      const inTower = x >= 12 && x < 36
      const towerTop = y < 4 && inTower && Math.floor((x - 12) / 4) % 2 === 0
      const tower = y >= 4 && y < 16 && inTower
      const wallTop = y >= 12 && y < 16 && Math.floor(x / 6) % 2 === 0
      const wall = y >= 16
      const door = x >= 19 && x < 29 && y >= 26 && (y >= 30 || Math.abs(x - 23.5) <= 3 + (y - 26))
      const window = y >= 7 && y < 12 && ((x >= 16 && x < 19) || (x >= 29 && x < 32))
      if (door || window) row += '3'
      else if (towerTop || tower || wallTop || wall) {
        const edge = x === 0 || x === width - 1 || (inTower && (x === 12 || x === 35) && y < 16)
        const mortar = y % 4 === 3 || (x + (Math.floor(y / 4) % 2) * 4) % 8 === 0
        row += edge ? '3' : mortar ? '2' : '1'
      } else row += '.'
    }
    rows.push(row)
  }
  return rows
}
